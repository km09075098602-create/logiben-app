// 祝日の計算のテスト(内閣府が発表している祝日と照らし合わせ)
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { holidaysOfYear, holidayName, holidaysBetween } from '../src/holidays.js';

test('2026年の祝日(内閣府の発表どおり)', () => {
  assert.deepEqual([...holidaysOfYear(2026).keys()], [
    '2026-01-01', '2026-01-12', '2026-02-11', '2026-02-23', '2026-03-20', '2026-04-29',
    '2026-05-03', '2026-05-04', '2026-05-05', '2026-05-06', // 5/6 は振替休日
    '2026-07-20', '2026-08-11', '2026-09-21', '2026-09-22', '2026-09-23', // 9/22 は国民の休日
    '2026-10-12', '2026-11-03', '2026-11-23',
  ]);
  assert.equal(holidayName('2026-05-06'), '振替休日');
  assert.equal(holidayName('2026-09-22'), '国民の休日');
});

test('2027年の祝日(内閣府の発表どおり)', () => {
  assert.deepEqual([...holidaysOfYear(2027).keys()], [
    '2027-01-01', '2027-01-11', '2027-02-11', '2027-02-23', '2027-03-21', '2027-03-22', // 3/22 は振替休日
    '2027-04-29', '2027-05-03', '2027-05-04', '2027-05-05',
    '2027-07-19', '2027-08-11', '2027-09-20', '2027-09-23', '2027-10-11', '2027-11-03', '2027-11-23',
  ]);
});

test('祝日でない日は null', () => {
  assert.equal(holidayName('2027-01-04'), null);
  assert.equal(holidayName('2026-11-03'), '文化の日');
});

test('期間内の祝日', () => {
  assert.deepEqual(holidaysBetween('2026-12-20', '2027-01-15'), [
    { date: '2027-01-01', name: '元日' },
    { date: '2027-01-11', name: '成人の日' },
  ]);
});
